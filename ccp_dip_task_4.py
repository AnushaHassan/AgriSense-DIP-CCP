# ── CELL 6: Otsu + K-means confusion matrices ─────────────────────────────────
from sklearn.metrics import confusion_matrix

# Subsample for confusion matrix (full image is too large)
rng = np.random.default_rng(42)
N_SAMPLE = 50000
