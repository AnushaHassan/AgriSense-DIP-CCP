    0.68,   # Feb 15  — jointing / stem elongation
    0.75,   # Mar 15  — heading / anthesis PEAK
    0.71,   # Apr 15  — grain filling
    0.48,   # May 15  — senescence
    0.20,   # Jun 15  — harvest / residue
    0.14,   # Jul 15  — bare soil
