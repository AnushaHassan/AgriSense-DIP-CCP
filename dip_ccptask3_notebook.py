def season_length(
    ndvi_series,
    dates,
    threshold=0.30
):
    active = np.where(ndvi_series > threshold)[0]

    if len(active) == 0:
        return np.nan

    start = dates[active[0]]
    end   = dates[active[-1]]

    return (
        start,
        end,
        (end-start).days
    )

